fn sample_fn(name: &str, fields: &[FieldIr], index: &Index<'_>) -> String {
    let mut out = format!("fn sample_{}() -> {name} {{\n    {name} {{\n", snake(name));
    for field in fields {
        out.push_str("        ");
        out.push_str(&field.rust_name);
        out.push_str(": ");
        out.push_str(&sample_expr(&field.ty, index));
        out.push_str(",\n");
    }
    out.push_str("    }\n}\n\n");
    out
}

fn roundtrip_fn(name: &str, fields: &[FieldIr]) -> String {
    let mut out = format!(
        "#[test]\nfn roundtrip_{}() {{\n    let value = sample_{}();\n    let json = serde_json::to_value(&value).unwrap();\n",
        snake(name),
        snake(name)
    );
    for field in fields {
        if !field.ty.starts_with("Option<") {
            out.push_str("    assert!(json.get(\"");
            out.push_str(&field.json_name);
            out.push_str("\").is_some());\n");
        }
    }
    out.push_str("    let back: ");
    out.push_str(name);
    out.push_str(" = serde_json::from_value(json).unwrap();\n    assert_eq!(value, back);\n}\n\n");
    out
}

fn sample_expr(ty: &str, index: &Index<'_>) -> String {
    if let Some(inner) = ty
        .strip_prefix("Option<")
        .and_then(|rest| rest.strip_suffix('>'))
    {
        let _ = inner;
        return "None".into();
    }
    if ty
        .strip_prefix("Vec<")
        .and_then(|rest| rest.strip_suffix('>'))
        .is_some()
    {
        return "Vec::new()".into();
    }
    match ty {
        "String" => "\"sample\".to_string()".into(),
        "bool" => "false".into(),
        "i64" => "0".into(),
        "f64" => "0.0".into(),
        "serde_json::Value" => "serde_json::Value::Null".into(),
        other if index.structs.contains_key(other) => format!("sample_{}()", snake(other)),
        other if index.aliases.contains_key(other) => {
            format!("<{other} as core::default::Default>::default()")
        }
        other => format!("compile_error!(\"no sample for {other}\")"),
    }
}

fn has_float(ty: &str, index: &Index<'_>) -> bool {
    if ty.contains("f64") {
        return true;
    }
    let mut current = ty.to_string();
    loop {
        if let Some(inner) = unwrap_known(&current) {
            current = inner;
            continue;
        }
        break;
    }
    if let Some(item) = index.structs.get(current.as_str()) {
        return item.fields.iter().any(|field| has_float(&field.ty, index));
    }
    if let Some(alias) = index.aliases.get(current.as_str()) {
        return alias.contains("f64");
    }
    false
}

fn unwrap_known(ty: &str) -> Option<String> {
    for wrapper in ["Option", "Vec"] {
        if let Some(inner) = ty.strip_prefix(&format!("{wrapper}<")) {
            if let Some(inner) = inner.strip_suffix('>') {
                if !inner.contains('<') {
                    return Some(inner.to_string());
                }
            }
        }
    }
    None
}

fn unwrap_angle<'a>(wrapper: &str, ty: &'a str) -> &'a str {
    ty.strip_prefix(&format!("{wrapper}<"))
        .and_then(|rest| rest.strip_suffix('>'))
        .unwrap_or(ty)
}

fn param_ty(ty: &str) -> String {
    if ty == "String" {
        "impl Into<String>".into()
    } else {
        ty.to_string()
    }
}

fn rust_doc(text: &str) -> String {
    let mut out = String::new();
    let cleaned = text.replace('\r', "");
    let source = if cleaned.trim().is_empty() {
        "Generated."
    } else {
        cleaned.trim()
    };
    for line in source.split('\n') {
        out.push_str("/// ");
        out.push_str(&escape_doc(line.trim_end()));
        out.push('\n');
    }
    out
}

fn indent_doc(text: &str) -> String {
    rust_doc(text)
        .lines()
        .map(|line| format!("    {line}\n"))
        .collect()
}

fn escape_doc(line: &str) -> String {
    line.replace("*/", "* /")
        .replace('[', "\\[")
        .replace(']', "\\]")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

fn module_name(category: &str) -> String {
    raw_ident(&category.to_ascii_lowercase().replace([' ', '-'], "_"))
}

fn pascal(snake_name: &str) -> String {
    snake_name
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect()
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (index, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if index > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    raw_ident(&out)
}

fn variant_ident(ident: &str) -> String {
    let trimmed = ident.strip_prefix("OBS_WEBSOCKET_").unwrap_or(ident);
    let pascal_name = if trimmed.contains('_') {
        pascal(&trimmed.to_ascii_lowercase())
    } else {
        trimmed.to_string()
    };
    raw_ident(&pascal_name)
}

fn raw_ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod",
        "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
        "trait", "true", "try", "type", "unsafe", "use", "where", "abstract", "become", "box",
        "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

fn parse_i64(value: &Value) -> Option<i64> {
    match value {
        Value::Number(number) => number
            .as_i64()
            .or_else(|| number.as_u64().map(|value| value as i64)),
        Value::String(text) => eval_bits(value, &BTreeMap::new())
            .map(|value| value as i64)
            .or_else(|| text.parse().ok()),
        _ => None,
    }
}

fn eval_bits(value: &Value, known: &BTreeMap<String, u32>) -> Option<u32> {
    match value {
        Value::Number(number) => number.as_u64().map(|value| value as u32),
        Value::String(text) => eval_expr(text.trim(), known),
        _ => None,
    }
}

fn eval_expr(expr: &str, known: &BTreeMap<String, u32>) -> Option<u32> {
    let expr = expr.trim().trim_matches(|ch| ch == '(' || ch == ')').trim();
    if let Some(rest) = expr.strip_prefix("1 << ") {
        let bits: u32 = rest.trim().parse().ok()?;
        return Some(1u32 << bits);
    }
    if expr.contains('|') {
        let mut acc = 0u32;
        for part in expr.split('|') {
            acc |= eval_expr(part.trim(), known)?;
        }
        return Some(acc);
    }
    if let Ok(number) = expr.parse::<u32>() {
        return Some(number);
    }
    known.get(expr).copied()
}

fn rustfmt(paths: impl Iterator<Item = PathBuf>) -> Result<(), String> {
    let paths: Vec<PathBuf> = paths.collect();
    if paths.is_empty() {
        return Ok(());
    }
    let status = Command::new("rustfmt")
        .arg("--edition")
        .arg("2024")
        .args(&paths)
        .status()
        .map_err(|error| format!("rustfmt: {error}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("rustfmt exited with {status}"))
    }
}

