fn emit_struct(
    name: &str,
    doc: &str,
    deprecated: bool,
    fields: &[FieldIr],
    index: &Index<'_>,
) -> String {
    let mut out = String::new();
    out.push_str(&rust_doc(doc));
    if deprecated {
        out.push_str("#[deprecated(note = \"deprecated by obs-websocket\")]\n");
    }
    out.push_str("#[derive(Debug, Clone, PartialEq");
    if !fields.iter().any(|field| has_float(&field.ty, index)) {
        out.push_str(", Eq");
    }
    out.push_str(", Serialize, Deserialize");
    if fields.is_empty() || fields.iter().all(|field| field.ty.starts_with("Option<")) {
        out.push_str(", Default");
    }
    out.push_str(")]\n#[non_exhaustive]\npub struct ");
    out.push_str(name);
    out.push_str(" {\n");
    for field in fields {
        out.push_str(&indent_doc(&field.doc));
        out.push_str("    #[serde(rename = \"");
        out.push_str(&field.json_name);
        out.push('"');
        if field.ty.starts_with("Option<") {
            out.push_str(", default, skip_serializing_if = \"Option::is_none\"");
        }
        out.push_str(")]\n    pub ");
        out.push_str(&field.rust_name);
        out.push_str(": ");
        out.push_str(&field.ty);
        out.push_str(",\n");
    }
    out.push_str("}\n\n");
    out.push_str(&emit_builder(name, fields));
    out.push('\n');
    out
}

fn emit_builder(name: &str, fields: &[FieldIr]) -> String {
    let mut out = String::new();
    out.push_str("impl ");
    out.push_str(name);
    out.push_str(" {\n    /// Creates a value.\n    #[must_use]\n    pub fn new(");
    let required: Vec<&FieldIr> = fields
        .iter()
        .filter(|field| !field.ty.starts_with("Option<"))
        .collect();
    for (position, field) in required.iter().enumerate() {
        if position > 0 {
            out.push_str(", ");
        }
        out.push_str(&field.rust_name);
        out.push_str(": ");
        out.push_str(&param_ty(&field.ty));
    }
    out.push_str(") -> Self {\n        Self {\n");
    for field in fields {
        out.push_str("            ");
        out.push_str(&field.rust_name);
        out.push_str(": ");
        if field.ty.starts_with("Option<") {
            out.push_str("None");
        } else if field.ty == "String" {
            out.push_str(&field.rust_name);
            out.push_str(".into()");
        } else {
            out.push_str(&field.rust_name);
        }
        out.push_str(",\n");
    }
    out.push_str("        }\n    }\n");
    for field in fields
        .iter()
        .filter(|field| field.ty.starts_with("Option<"))
    {
        let inner = unwrap_angle("Option", &field.ty);
        out.push_str("    /// Sets `");
        out.push_str(&field.json_name);
        out.push_str("`.\n    #[must_use]\n    pub fn ");
        out.push_str(&field.rust_name);
        out.push_str("(mut self, value: ");
        out.push_str(&param_ty(inner));
        out.push_str(") -> Self {\n        self.");
        out.push_str(&field.rust_name);
        out.push_str(" = Some(");
        if inner == "String" {
            out.push_str("value.into()");
        } else {
            out.push_str("value");
        }
        out.push_str(");\n        self\n    }\n");
    }
    out.push_str("}\n");
    out
}

fn protocol_fields(
    owner: &str,
    side: &str,
    fields: &[ProtocolField],
    overrides: &Overrides,
) -> Vec<FieldIr> {
    fields
        .iter()
        .filter(|field| !field.value_name.contains('.'))
        .map(|field| {
            let key = format!("{owner}.{side}.{}", field.value_name);
            let ty = if let Some(overridden) = overrides.fields.get(&key) {
                overridden.clone()
            } else {
                map_type(
                    &field.value_name,
                    &field.value_type,
                    field.value_optional || nullable(&field.value_description),
                )
            };
            FieldIr {
                json_name: field.value_name.clone(),
                rust_name: snake(&field.value_name),
                ty,
                doc: field_doc(field),
            }
        })
        .collect()
}

fn override_fields(item: &StructDef) -> Vec<FieldIr> {
    item.fields
        .iter()
        .map(|field| FieldIr {
            json_name: field.name.clone(),
            rust_name: field
                .rust_name
                .clone()
                .unwrap_or_else(|| snake(&field.name)),
            ty: field.ty.clone(),
            doc: field.doc.clone(),
        })
        .collect()
}

fn map_type(name: &str, value_type: &str, optional: bool) -> String {
    let base = match value_type {
        "String" => "String",
        "Boolean" => "bool",
        "Number" if FLOAT_FIELDS.contains(&name) => "f64",
        "Number" => "i64",
        "Object" | "Any" => "serde_json::Value",
        "Array<String>" => "Vec<String>",
        "Array<Boolean>" => "Vec<bool>",
        "Array<Number>" if FLOAT_FIELDS.contains(&name) => "Vec<f64>",
        "Array<Number>" => "Vec<i64>",
        "Array<Object>" | "Array<Any>" => "Vec<serde_json::Value>",
        _ => "serde_json::Value",
    };
    if optional {
        format!("Option<{base}>")
    } else {
        base.to_string()
    }
}

fn nullable(description: &str) -> bool {
    description.contains("`null`")
}

fn field_doc(field: &ProtocolField) -> String {
    let mut doc = field.value_description.clone();
    if let Some(restrictions) = &field.value_restrictions {
        if !doc.is_empty() {
            doc.push(' ');
        }
        doc.push_str("Restrictions: ");
        doc.push_str(restrictions);
        doc.push('.');
    }
    if let Some(behavior) = &field.value_optional_behavior {
        if !behavior.is_empty() && behavior != "N/A" && behavior != "Unknown" && behavior != "None"
        {
            if !doc.is_empty() {
                doc.push(' ');
            }
            doc.push_str("When omitted: ");
            doc.push_str(behavior);
            doc.push('.');
        }
    }
    if doc.is_empty() {
        field.value_name.clone()
    } else {
        doc
    }
}

